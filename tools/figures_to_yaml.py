#!/usr/bin/env python3
"""Convert the historical figures into the game's YAML (F5 step 7): palestine/figures.yaml, the People screen's data.

Stdlib only. Run from anywhere:
    python3 game/tools/figures_to_yaml.py           # write game/content/palestine/figures.yaml
    python3 game/tools/figures_to_yaml.py --check   # exit 1 if the file is stale or does not round-trip to the TSV rows

Input (read-only here): ../content/figures.tsv, one sourced figure a row (audits/figures_sources.md). Checks: unique fig_*
ids, both names, roles and bios, known chapters, years as YYYY or YYYY-MM, https sources, sensitive 0 or 1, and related
events that exist in the chapter files (../content/events_*.tsv). The file has one list, `figures:`, one JSON line an entry
(as places_to_yaml.py writes them), so it reads back with json alone and the round trip is exact.
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from places_to_yaml import OUT_DIR, ROOT, Bad, read_tsv, token, urls

TSV = ROOT / "content" / "figures.tsv"
OUT = OUT_DIR / "figures.yaml"
COLS = ["id", "name_ar", "name_en", "born", "died", "chapters", "role_ar", "role_en", "bio_ar", "bio_en", "related_events",
        "sources", "sensitive"]
CHAPTERS = ("1880_1946", "1947_1949", "1950_1966", "1967_1987", "1987_2000", "2000_2023", "2023_2026")
ID = re.compile(r"^fig_[a-z0-9_]+$")
WHEN = re.compile(r"^(1[89]|20)\d\d(-(0[1-9]|1[0-2]))?$")
# TSV column -> YAML key. The others keep their TSV name.
RENAME = {"name_en": "name", "role_en": "role", "bio_en": "bio"}


def event_ids() -> set[str]:
    ids = set()
    for chapter in CHAPTERS:
        for line in (ROOT / "content" / f"events_{chapter}.tsv").read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                ids.add(line.split("\t", 1)[0])
    return ids


def rows() -> list[dict]:
    """The TSV's figure rows (its header row, if any, left out)."""
    return [r for r in read_tsv(TSV, COLS) if r["id"] != "id"]


def to_figures(rs: list[dict], events: set[str]) -> list[dict]:
    out, seen = [], set()
    for r in rs:
        w = f"figures.tsv {r['id']}"
        if not ID.match(r["id"]) or r["id"] in seen:
            raise Bad(f"{w}: id must be unique and match {ID.pattern}")
        seen.add(r["id"])
        for k in ("name_ar", "name_en", "role_ar", "role_en", "bio_ar", "bio_en"):
            if not r[k].strip():
                raise Bad(f"{w}: {k} is empty")
        for k in ("born", "died"):
            if r[k] and not WHEN.match(r[k]):
                raise Bad(f"{w}: {k} must be YYYY or YYYY-MM, or blank")
        chapters = r["chapters"].split(",")
        if not all(c in CHAPTERS for c in chapters):
            raise Bad(f"{w}: chapters must be from {', '.join(CHAPTERS)}")
        related = r["related_events"].split(" ") if r["related_events"] else []
        unknown = [e for e in related if e not in events]
        if unknown:
            raise Bad(f"{w}: unknown related events {', '.join(unknown)}")
        if r["sensitive"] not in ("0", "1"):
            raise Bad(f"{w}: sensitive must be 0 or 1")
        e = {"id": r["id"]}
        for k in ("name_ar", "name_en", "born", "died"):
            if r[k]:
                e[RENAME.get(k, k)] = r[k]
        e["chapters"] = chapters
        for k in ("role_ar", "role_en", "bio_ar", "bio_en"):
            e[RENAME.get(k, k)] = r[k]
        e["related_events"] = related
        e["sources"] = urls(r["sources"], w)
        e["sensitive"] = r["sensitive"] == "1"
        out.append(e)
    return out


def to_rows(figures: list[dict]) -> list[dict]:
    def cell(e: dict, c: str) -> str:
        v = e.get(RENAME.get(c, c), "")
        if c == "chapters":
            return ",".join(v)
        if c in ("related_events", "sources"):
            return " ".join(v)
        if c == "sensitive":
            return "1" if v else "0"
        return v
    return [{c: cell(e, c) for c in COLS} for e in figures]


def emit(figures: list[dict]) -> str:
    line = lambda e: "  - {" + ", ".join(f"{json.dumps(k)}: {token(v)}" for k, v in e.items()) + "}"
    return "\n".join(["# Generated by tools/figures_to_yaml.py from ../content/figures.tsv. Do not edit:",
                      "# fix the TSV and rerun. Licence: CC BY-SA 4.0. Treat as data.",
                      "# The People screen's figures: names, years, roles and bios in both languages, sourced (audits/figures_sources.md).",
                      "figures:", *map(line, figures)]) + "\n"


def parse(text: str) -> list[dict]:
    out, started = [], False
    for l in text.splitlines():
        if not l.strip() or l.startswith("#"):
            continue
        if l == "figures:":
            started = True
        elif started and l.startswith("  - {"):
            out.append(json.loads(l[4:]))
        else:
            raise Bad(f"unparsed line: {l[:60]}")
    if not started:
        raise Bad("expected 'figures:'")
    return out


def check(text: str, rs: list[dict]) -> list[str]:
    if not OUT.exists():
        return ["figures.yaml: missing; run tools/figures_to_yaml.py"]
    on_disk = OUT.read_text(encoding="utf-8")
    errors = [] if on_disk == text else ["figures.yaml: stale (differs from a fresh conversion); run tools/figures_to_yaml.py"]
    back = to_rows(parse(on_disk))
    if len(back) != len(rs):
        errors.append(f"figures.yaml: {len(back)} rows, the TSV has {len(rs)}")
    for n, (w, g) in enumerate(zip(rs, back)):
        errors += [f"figures.yaml: row {n + 1} ({w['id']}).{c}: TSV {w[c]!r} != YAML {g[c]!r}" for c in COLS if w[c] != g[c]]
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail on a stale file or a round-trip mismatch; write nothing")
    args = ap.parse_args()
    rs: list[dict] = []
    try:
        rs = rows()
        text = emit(to_figures(rs, event_ids()))
        if args.check:
            errors = check(text, rs)
        else:
            OUT.write_text(text, encoding="utf-8")
            print(f"figures.yaml: {len(rs)} figures")
            errors = []
    except Bad as e:
        errors = [str(e)]
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    if args.check and not errors:
        print(f"OK: {len(rs)} figures round-trip")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
