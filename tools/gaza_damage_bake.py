"""The destruction of Gaza, 2023-2025, as UNOSAT's satellite images record it -> the layer the terrain draws over the strip
(content/map/gaza_damage_2023.yaml; GazaDamage and StoryOfTheLandEra.hlsl in Unity).

Usage: uv run tools/gaza_damage_bake.py --gdb <dir>/UNOSAT_GazaStrip_CDA_11October2025.gdb   (the download, kept outside the
       repository: SOURCE has its URL and SHA-256; delete it afterwards)
       uv run tools/gaza_damage_bake.py [--check]   (rebakes the texture from the committed cells)

Source: UNOSAT's comprehensive damage assessment of 11 October 2025 (CE20231007PSE), 198,308 structures each with its class
on every image date from 15 October 2023 (Main_Damage_Site_Class_k at SensorDate_k, k = 1..14; 1 destroyed, 2 severe, 3
moderate, 4 and 11 possible damage). Raw points are not kept: each structure counts once in its CELL (about 284 x 298 m,
two by two texels of tools/occupation_bake.py's grid), at the first image that shows it damaged (any class) and at the first
that shows it destroyed. A damaged structure was damaged between that image and the one before (from 7 October 2023 for
the first): the image dates are all the data says about when.
The texture (one texel a cell): r the image (1..14) by which half the cell's damaged structures had been recorded, g the
same for destroyed ones (0: none), b how many were damaged (DENSITY_CAP or more: 255), a the destroyed share of them. The
sim never reads the output (display only).
"""
import argparse
import base64
import io
import json
import struct
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "content" / "map" / "gaza_damage_2023.yaml"
SOURCE = {"title": "UNOSAT Gaza Strip Comprehensive Damage Assessment - 11 October 2025", "by": "UNOSAT (UNITAR)",
          "page": "https://data.humdata.org/dataset/unosat-gaza-strip-comprehensive-damage-assessment-11-october-2025",
          "url": "https://unosat.org/static/unosat_filesystem/4213/OCHA-CBPF-OPT-031_UNOSAT_Gaza_Strip_CDA_11October2025_GDB.zip",
          "sha256": "43dab8c9bb6012eba2a65d2e74413e49d43c906e13e555cc8a34aaa73fe6fa48", "licence": "CC-BY-SA", "checked": "2026-10-22"}
LAYER = "Damage_Sites_GazaStrip_20251011"
IMAGES = 14
# UNOSAT's own totals on 11 October 2025 (the dataset's HDX page): the bake fails if the file disagrees.
PUBLISHED = {"destroyed": 123464, "severe": 17116, "moderate": 33857, "possible": 23836}
CLASS = {1: "destroyed", 2: "severe", 3: "moderate", 4: "possible", 11: "possible"}
GRID = {"lon0": 34.20, "lat0": 31.20, "dlon": 0.003, "dlat": 0.0027, "nx": 130, "ny": 156}
DENSITY_CAP = 60
WAR_FROM = "2023-10-07"
# Months with no new destruction drawn (no smoke): the truce of 24 November - 1 December 2023 (chapter event
# gz_2023_11_truce), the ceasefire of 19 January - 18 March 2025 (gz_2025_01_truce_return, gz_2025_03_resumption), and
# from the ceasefire of 10 October 2025 (gz_2025_10_ceasefire), after which UNOSAT's file has no image.
QUIET = [("2023-11-24", "2023-12-01"), ("2025-01-19", "2025-03-18"), ("2025-10-10", None)]
HEADER = ("# Generated by tools/gaza_damage_bake.py from UNOSAT's damage assessment of 11 October 2025 (CC BY-SA; the cells below\n"
          "# hold every structure once, no raw points). Do not edit by hand: rerun the tool. Display only (GazaDamage): the sim never\n"
          "# reads this file.\n")


def wkb_lonlat(b: bytes) -> tuple[float, float]:
    """A WKB point's x, y (any byte order, with or without Z)."""
    fmt = "<dd" if b[0] == 1 else ">dd"
    return struct.unpack_from(fmt, b, 5)


def read_gdb(gdb: Path) -> tuple[list, list]:
    """(image dates, [(lon, lat, first damaged image, first destroyed image or 0, class on the last image)])."""
    from pyogrio.raw import read
    cols = [f"{f}{'' if k == 1 else '_' + str(k)}" for k in range(1, IMAGES + 1) for f in ("SensorDate", "Main_Damage_Site_Class")]
    meta, _, geom, fields = read(str(gdb), layer=LAYER, columns=cols, read_geometry=True)
    col = dict(zip(meta["fields"], fields))
    dates = []
    for k in range(1, IMAGES + 1):
        sd = col["SensorDate" if k == 1 else f"SensorDate_{k}"]
        c = Counter(str(x)[:10] for x in sd if str(x) != "NaT")
        dates.append(c.most_common(1)[0][0])   # a few sites carry another day's image; the image date is the common one
    sites = []
    for n in range(len(geom)):
        first = destroyed = 0
        last = 0
        for k in range(1, IMAGES + 1):
            v = col["Main_Damage_Site_Class" if k == 1 else f"Main_Damage_Site_Class_{k}"][n]
            cls = 0 if v is None or v != v else int(v)
            if cls in CLASS and not first:
                first = k
            if cls == 1 and not destroyed:
                destroyed = k
            if k == IMAGES:
                last = cls
        lon, lat = wkb_lonlat(geom[n])
        sites.append((lon, lat, first, destroyed, last))
    return dates, sites


def cells_of(sites: list) -> dict:
    """{(i, j): [damaged per first image (IMAGES), destroyed per first image (IMAGES)]}, j = 0 the north row."""
    g = GRID
    lat1 = g["lat0"] + g["ny"] * g["dlat"]
    out = {}
    for lon, lat, first, destroyed, _ in sites:
        if not first and not destroyed:
            continue
        i, j = int((lon - g["lon0"]) / g["dlon"]), int((lat1 - lat) / g["dlat"])
        if not (0 <= i < g["nx"] and 0 <= j < g["ny"]):
            raise SystemExit(f"a damaged structure at {lon:.5f}, {lat:.5f} lies outside the grid")
        c = out.setdefault((i, j), [[0] * IMAGES, [0] * IMAGES])
        c[0][(first or destroyed) - 1] += 1
        if destroyed:
            c[1][destroyed - 1] += 1
    return out


def half_by(counts: list) -> int:
    """The image (1..IMAGES) by which half the counts are recorded; 0 for none."""
    total, run = sum(counts), 0
    for k, n in enumerate(counts, 1):
        run += n
        if total and 2 * run >= total:
            return k
    return 0


def texture(cells: dict) -> str:
    g = GRID
    px = np.zeros((g["ny"], g["nx"], 4), dtype=np.uint8)
    for (i, j), (dmg, des) in cells.items():
        n, x = sum(dmg), sum(des)
        px[j, i] = (half_by(dmg), half_by(des), min(255, (n * 255 + DENSITY_CAP // 2) // DENSITY_CAP), (x * 255 + n // 2) // n if n else 0)
    buf = io.BytesIO()
    Image.fromarray(px, "RGBA").save(buf, "PNG", compress_level=9)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def runs(counts: list) -> str:
    """'k:n k:n' for the images with a count (compact cell rows)."""
    return " ".join(f"{k}:{n}" for k, n in enumerate(counts, 1) if n)


def parse_runs(text: str) -> list:
    out = [0] * IMAGES
    for tok in text.split():
        k, n = tok.split(":")
        out[int(k) - 1] = int(n)
    return out


def render(dates: list, cells: dict, totals: dict) -> str:
    q = json.dumps
    out = [HEADER, "layer: gaza_damage_2023\n", f"title: {q('The destruction of Gaza as UNOSAT satellite images record it, October 2023 - October 2025')}\n"]
    out += [f"{k}: {v}\n" for k, v in GRID.items()]
    out.append(f"density_cap: {DENSITY_CAP}\n")
    out.append(f"war_from: {WAR_FROM}   # the war's first day; the first image's damage happened from then\n")
    out.append("images: [" + ", ".join(dates) + "]   # UNOSAT's image dates, 1..14\n")
    out.append("quiet:   # months inside these spans draw no new destruction (truces and ceasefires; chapter events)\n")
    for a, b in QUIET:
        out.append(f"  - [{a}, {b or 'null'}]\n")
    out.append(f"source: {{ title: {q(SOURCE['title'])}, by: {q(SOURCE['by'])}, page: {q(SOURCE['page'])}, url: {q(SOURCE['url'])}, "
               f"sha256: {SOURCE['sha256']}, licence: {SOURCE['licence']}, checked: {SOURCE['checked']} }}\n")
    out.append("totals: { " + ", ".join(f"{k}: {v}" for k, v in totals.items()) + " }   # on the last image, by class; ever: damaged or destroyed on any image\n")
    out.append("cells:   # [i, j, damaged by first image, destroyed by first image] ('k:n': n structures first so on image k), i east, j south\n")
    for (i, j) in sorted(cells, key=lambda c: (c[1], c[0])):
        dmg, des = cells[(i, j)]
        out.append(f"  - [{i}, {j}, \"{runs(dmg)}\", \"{runs(des)}\"]\n")
    out.append(f"tex: {texture(cells)}\n")
    return "".join(out)


def from_file(text: str) -> tuple[list, dict, dict]:
    import yaml12
    doc = yaml12.load(text[:text.index("\ntex: ")])
    cells = {(int(i), int(j)): [parse_runs(a), parse_runs(b)] for i, j, a, b in doc["cells"]}
    return [str(d) for d in doc["images"]], cells, dict(doc["totals"])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gdb", type=Path, help="UNOSAT's file geodatabase (outside the repository)")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.gdb:
        if ROOT in a.gdb.resolve().parents:
            raise SystemExit("--gdb must be outside the repository")
        dates, sites = read_gdb(a.gdb)
        final = Counter(CLASS[s[4]] for s in sites if s[4] in CLASS)
        if dict(final) != PUBLISHED:
            raise SystemExit(f"the file's last-image totals {dict(final)} differ from UNOSAT's published {PUBLISHED}")
        cells = cells_of(sites)
        totals = {**PUBLISHED, "ever_damaged": sum(sum(d) for d, _ in cells.values()), "ever_destroyed": sum(sum(x) for _, x in cells.values())}
    else:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        dates, cells, totals = from_file(OUT.read_text(encoding="utf-8"))
    text = render(dates, cells, totals)
    if a.check:
        if OUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is stale: rerun tools/gaza_damage_bake.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB, {len(cells)} cells; {totals})")


if __name__ == "__main__":
    main()
