"""The occupation's map layers (content/map/occupation_1967.geojson and oslo_areas_1995.geojson, the true shapes:
tools/occupation_digitise.py) -> the layer the terrain draws over the West Bank and Gaza (content/map/occupation_layers.yaml;
OccupationLayers and StoryOfTheLandEra.hlsl in Unity).

Usage: uv run tools/occupation_bake.py [--check]   (--check fails when the committed file is stale)

Unlike the 1948 layers this one is not snapped to hexes: a hex is 5 km and Gaza's access-restricted band is 100-1,000 m, so
the shapes are drawn as they are, from three textures over GRID (about 142 x 149 m a texel) that the terrain shader reads:
  tex1 (filtered)  r the West Bank, g the Gaza Strip, b Oslo Area A, a Oslo Area B: each texel's covered share (SS x SS
                   samples), so the edges stay soft when filtered
  tex2 (filtered)  r distance to the wall as built (OCHA's 'constructed'), g to the wall not yet built (under construction or
                   planned), b to the nearest settlement's point, in DIST_UNIT_M metres up to 255 (2,040 m); a Gaza's access-
                   restricted area: half the share inside the 300 m band plus half the share inside the 1,000 m band, so 1
                   is within 300 m of the fence, 0.5 between 300 and 1,000 m (times the strip's share: inside it only)
  tex3 (r exact)   r the nearest settlement's code (read texel-exact, never filtered): its founding year - 1900, plus 128 for
                   one emptied in August 2005; g the built-up areas' share; b distance to the West Bank's outline; a
                   distance to Gaza's land border (its outline where the access-restricted bands touch it: the fence)
Distances are metres on the game's own equirectangular projection (hexgrid.km_per_deg_lon over hexes.json's bounds, as
GeoFrame), so a line drawn n metres wide is n metres of the map. Each texture is a lossless PNG, base64 in the YAML (the
content bundle carries text only). The dates each layer is drawn from are DATES, with their sources. Deterministic: float64
in a fixed order, features in file order. The sim never reads the output (display only: the content hash and the goldens do
not move).
"""
import base64
import io
import json
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from rasterio import features as rf
from rasterio.transform import Affine

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hexgrid  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "content" / "map"
SOURCE = MAP / "occupation_1967.geojson"
OSLO = MAP / "oslo_areas_1995.geojson"
OUT = MAP / "occupation_layers.yaml"
GRID = {"lon0": 34.20, "lat0": 31.20, "dlon": 0.0015, "dlat": 0.00135, "nx": 934, "ny": 1023}
SS = 4
DIST_UNIT_M = 8.0
NEAR_ARA_M = 150.0
# Each layer's first day (and the settlements' last), with what says so. The chapter events named hold the opened sources.
DATES = [
    ("occupied_from", "1967-06-05", "Israel occupied the West Bank, East Jerusalem and the Gaza Strip between 5 and 10 June 1967 (chapter event e1967_06_naksa)"),
    ("fence_from", "1994-01-01", "Gaza's perimeter fence, about 60 km, built after the Oslo Accords in 1994 (Al Jazeera, 6 Jul 2008, https://www.aljazeera.com/news/2008/7/6/background-the-separation-barrier); drawn on the strip's land border as mapped today"),
    ("oslo_from", "1995-09-28", "Oslo II signed in Washington on 28 September 1995 (chapter event e1995_09_oslo2); the areas as the Palestinian Ministry of Planning mapped them (HDX, dataset date 2004)"),
    ("ara_from", "2000-09-01", "Since September 2000 Israel has restricted Palestinian access to the land along Gaza's fence (OCHA factsheet, August 2018, https://www.un.org/unispal/wp-content/uploads/2018/08/OCHAHUMACCESSGAZA_030818.pdf); the bands as OCHA mapped them in October 2023"),
    ("wall_from", "2002-06-01", "Building of the wall began in June 2002 (chapter event e2002_06_wall; Al Jazeera, 6 Jul 2008); until wall_mapped_from the route OCHA mapped in January 2018 is drawn as being built"),
    ("evacuated_on", "2005-08-22", "All 21 Gaza settlements emptied by 22 August 2005, and four in the northern West Bank (Al Jazeera, 16 Sep 2025, https://www.aljazeera.com/news/2025/9/16/mapping-the-21-illegal-settlements-israel-had-in-gaza-20-years-ago; chapter event e2005_08_disengagement)"),
    ("footprints_from", "2011-01-01", "The settlements' built-up areas as Peace Now mapped them from 2011 aerial photos"),
    ("wall_mapped_from", "2018-01-01", "OCHA's map of the wall, January 2018: constructed, under construction and planned"),
]
HEADER = ("# Generated by tools/occupation_bake.py from occupation_1967.geojson and oslo_areas_1995.geojson (the true shapes,\n"
          "# tools/occupation_digitise.py). Do not edit by hand: rerun the tool. Display only (OccupationLayers): the sim never reads\n"
          "# this file. Three lossless PNG textures over the grid below (tools/occupation_bake.py says what each channel holds).\n"
          "# Status draft, owner-verify.\n")


def metres_per_degree() -> tuple[float, float]:
    """The game world's metres per degree of longitude and latitude (GeoFrame over hexes.json's bounds)."""
    b = json.loads((MAP / "hexes.json").read_text())["bounds"]
    return hexgrid.km_per_deg_lon(b) * 1000.0, hexgrid.KM_PER_DEG_LAT * 1000.0


def lat1() -> float:
    return GRID["lat0"] + GRID["ny"] * GRID["dlat"]


def coverage(geoms: list) -> np.ndarray:
    """uint8 share (0-255) of each texel inside any of the polygons, row 0 the north edge."""
    out = np.zeros((GRID["ny"], GRID["nx"]), dtype=np.uint8)
    if not geoms:
        return out
    t = Affine(GRID["dlon"] / SS, 0.0, GRID["lon0"], 0.0, -GRID["dlat"] / SS, lat1())
    fine = rf.rasterize(((g, 1) for g in geoms), out_shape=(GRID["ny"] * SS, GRID["nx"] * SS), transform=t, fill=0, dtype="uint8")
    share = fine.reshape(GRID["ny"], SS, GRID["nx"], SS).sum(axis=(1, 3), dtype=np.int32)
    return ((share * 255 + SS * SS // 2) // (SS * SS)).astype(np.uint8)


def segments(lines: list) -> np.ndarray:
    """[[x0, y0, x1, y1], ...] in metres east and north of the grid's corner, from lon/lat polylines."""
    mx, my = metres_per_degree()
    out = []
    for coords in lines:
        p = np.array(coords, dtype=np.float64)[:, :2]
        xy = np.column_stack(((p[:, 0] - GRID["lon0"]) * mx, (p[:, 1] - GRID["lat0"]) * my))
        if len(xy) >= 2:
            out.append(np.hstack((xy[:-1], xy[1:])))
    return np.vstack(out) if out else np.zeros((0, 4))


def distance(segs: np.ndarray, points: np.ndarray | None = None) -> tuple[np.ndarray, np.ndarray]:
    """(uint8 distance in DIST_UNIT_M up to 255, int32 index of the nearest feature or -1) at each texel centre: to the
    segments, or, with points ([[x, y], ...]), to the points (a point is a segment of length 0)."""
    if points is not None:
        segs = np.hstack((points, points))
    mx, my = metres_per_degree()
    sx, sy = GRID["dlon"] * mx, GRID["dlat"] * my
    reach = 255 * DIST_UNIT_M
    best = np.full((GRID["ny"], GRID["nx"]), np.inf)
    who = np.full((GRID["ny"], GRID["nx"]), -1, dtype=np.int32)
    for k, (x0, y0, x1, y1) in enumerate(segs):
        i0 = max(0, int(math.floor((min(x0, x1) - reach) / sx))); i1 = min(GRID["nx"], int(math.ceil((max(x0, x1) + reach) / sx)) + 1)
        j0 = max(0, int(math.floor((min(y0, y1) - reach) / sy))); j1 = min(GRID["ny"], int(math.ceil((max(y0, y1) + reach) / sy)) + 1)
        if i0 >= i1 or j0 >= j1:
            continue
        cx = (np.arange(i0, i1, dtype=np.float64) + 0.5) * sx
        cy = (np.arange(j0, j1, dtype=np.float64) + 0.5) * sy
        px, py = np.meshgrid(cx, cy)
        dx, dy = x1 - x0, y1 - y0
        ll = dx * dx + dy * dy
        t = np.zeros_like(px) if ll == 0 else np.clip(((px - x0) * dx + (py - y0) * dy) / ll, 0.0, 1.0)
        d = np.hypot(px - (x0 + t * dx), py - (y0 + t * dy))
        rows = slice(GRID["ny"] - j1, GRID["ny"] - j0)   # row 0 is the north edge
        d = d[::-1]
        cur = best[rows, i0:i1]
        closer = d < cur
        cur[closer] = d[closer]
        who[rows, i0:i1][closer] = k
    q = np.minimum(np.round(best / DIST_UNIT_M), 255).astype(np.uint8)
    who[best > reach] = -1
    return q, who


def rings(geom: dict) -> list:
    """The exterior rings of a Polygon or MultiPolygon."""
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    return [p[0] for p in polys]


def lines(geom: dict) -> list:
    return [geom["coordinates"]] if geom["type"] == "LineString" else list(geom["coordinates"])


def land_border(gaza: dict, ara: list) -> list:
    """Gaza's outline where the access-restricted bands touch it (the fence on the land border), as polylines: the coast
    and the stretches the bands leave out are not drawn."""
    mx, my = metres_per_degree()
    near = coverage(ara)
    out, run = [], []
    for ring in rings(gaza):
        for a, b in zip(ring[:-1], ring[1:]):
            lon, lat = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
            hit = False
            for dj in (-1, 0, 1):   # within about a texel of the bands (NEAR_ARA_M)
                for di in (-1, 0, 1):
                    i = int((lon - GRID["lon0"]) / GRID["dlon"]) + di
                    j = int((lat1() - lat) / GRID["dlat"]) + dj
                    if 0 <= i < GRID["nx"] and 0 <= j < GRID["ny"] and near[j, i] > 0:
                        hit = True
            if hit:
                run = run or [a]
                run.append(b)
            elif run:
                out.append(run); run = []
        if run:
            out.append(run); run = []
    return out


def png(channels: list) -> str:
    """Base64 of a lossless RGBA PNG from four uint8 arrays (row 0 north), byte-identical for the same input."""
    buf = io.BytesIO()
    Image.fromarray(np.dstack(channels), "RGBA").save(buf, "PNG", compress_level=9)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def settlement_code(p: dict) -> int:
    code = p["from_year"] - 1900
    if not 0 < code < 128:
        raise SystemExit(f"settlement {p['name']}: founding year {p['from_year']} cannot be coded")
    return code + (128 if p["until"] else 0)


def bake(source: dict, oslo: dict) -> dict:
    by = lambda kind: [f for f in source["features"] if f["properties"]["kind"] == kind]
    terr = {f["properties"]["id"]: f["geometry"] for f in by("territory")}
    ara = {f["properties"]["band_m"]: f["geometry"] for f in by("ara")}
    pts = by("settlement")
    mx, my = metres_per_degree()
    xy = np.array([[(f["geometry"]["coordinates"][0] - GRID["lon0"]) * mx, (f["geometry"]["coordinates"][1] - GRID["lat0"]) * my]
                   for f in pts], dtype=np.float64).reshape(-1, 2)
    dot, who = distance(None, xy)
    codes = np.array([settlement_code(f["properties"]) for f in pts], dtype=np.uint8)
    code = np.where(who >= 0, codes[np.maximum(who, 0)] if len(codes) else 0, 0).astype(np.uint8)
    built = [f["geometry"] for f in by("barrier") if f["properties"]["status"] == "constructed"]
    unbuilt = [f["geometry"] for f in by("barrier") if f["properties"]["status"] != "constructed"]
    inner = [ara[b] for b in sorted(ara) if b <= 300]
    gaza_cov = coverage([terr["gaza"]])
    ara_level = (coverage(inner).astype(np.uint32) + coverage(list(ara.values())))   # 0..510
    ara_level = ((ara_level * gaza_cov + 255) // 510).astype(np.uint8)   # inside the strip's outline only (the two sources differ by metres)
    oslo_a = [f["geometry"] for f in oslo["features"] if f["properties"]["area"] == "A"]
    oslo_b = [f["geometry"] for f in oslo["features"] if f["properties"]["area"] == "B"]
    tex1 = [coverage([terr["west_bank"]]), gaza_cov, coverage(oslo_a), coverage(oslo_b)]
    tex2 = [distance(segments([c for g in built for c in lines(g)]))[0], distance(segments([c for g in unbuilt for c in lines(g)]))[0],
            dot, ara_level]
    tex3 = [code, coverage([f["geometry"] for f in by("settlement_area")]),
            distance(segments(rings(terr["west_bank"])))[0], distance(segments(land_border(terr["gaza"], list(ara.values()))))[0]]
    return {"tex1": png(tex1), "tex2": png(tex2), "tex3": png(tex3), "settlements": [f["properties"] for f in pts]}


def render(source: dict, oslo: dict, baked: dict) -> str:
    q = lambda s: json.dumps(s, ensure_ascii=False)
    out = [HEADER, "layer: occupation_1967\n",
           f"title: {q('The occupation on the map, June 1967 on')}\n",
           f"line: {q('True shapes (content/map/occupation_1967.geojson, oslo_areas_1995.geojson), not hex-snapped; textures of about 142 x 149 m a texel.')}\n",
           "# The grid: texel (0, 0) is the north-west corner; lon = lon0 + (i + 0.5) dlon, lat = lat0 + (ny - j - 0.5) dlat\n"]
    out += [f"{k}: {v}\n" for k, v in GRID.items()]
    out.append(f"dist_unit_m: {DIST_UNIT_M:g}\n")
    out.append("# Each layer's first day: the facts and their sources\n")
    for k, d, why in DATES:
        out.append(f"{k}: {d}   # {why}\n")
    srcs = source["storyoftheland"]["sources"] + oslo["storyoftheland"]["sources"]
    out.append("sources:   # the open datasets the shapes come from (licence as the publisher gives it)\n")
    for s in srcs:
        out.append(f"  - {{ key: {s['key'] if 'key' in s else 'wikidata'}, title: {q(s['title'])}, by: {q(s['by'])}, page: {q(s['page'])}, licence: {s['licence']}, checked: {s['checked']} }}\n")
    out.append("settlements:   # the points drawn, in tex3's order: from_year (Wikidata, or 2011: the aerial photos), until (emptied)\n")
    for p in baked["settlements"]:
        out.append(f"  - {{ name: {q(p['name'])}, from_year: {p['from_year']}, until: {p['until'] or 'null'}, basis: {p['basis']} }}\n")
    for k in ("tex1", "tex2", "tex3"):
        out.append(f"{k}: {baked[k]}\n")
    return "".join(out)


def build() -> str:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    oslo = json.loads(OSLO.read_text(encoding="utf-8")) if OSLO.exists() else {"storyoftheland": {"sources": []}, "features": []}
    return render(source, oslo, bake(source, oslo))


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is stale: run uv run tools/occupation_bake.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
