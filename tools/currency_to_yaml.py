#!/usr/bin/env python3
"""Convert the currencies and the place regions into the game's YAML: palestine/currency.yaml.

Stdlib only. Run from anywhere:
    python3 game/tools/currency_to_yaml.py           # write game/content/palestine/currency.yaml
    python3 game/tools/currency_to_yaml.py --check   # exit 1 if the file is stale or does not round-trip to the TSV rows

Inputs (read-only here):
  ../content/currency.tsv        the money families used, one row per period and region (national, inside_1948, west_bank, gaza)
  ../content/place_regions.tsv   the places outside the 1949 lines (west_bank, gaza); every other place is inside_1948
  ../unity/Assets/StreamingAssets/map/places.tsv   only to check that each place_regions id exists
The file has two lists, `currencies:` and `regions:`, one JSON line an entry (as places_to_yaml.py writes them). Checks: periods
of one region never overlap and never overlap a national period, so a family's region and month name one currency at most.
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from places_to_yaml import MAP_TSV, OUT_DIR, PLACE_COLS, ROOT, Bad, Num, read_tsv, token, urls

CUR_TSV = ROOT / "content" / "currency.tsv"
REG_TSV = ROOT / "content" / "place_regions.tsv"
OUT = OUT_DIR / "currency.yaml"
CUR_COLS = ["id", "from_year", "from_month", "to_year", "to_month", "region", "name_ar", "name_en", "symbol_ar", "symbol_en",
            "subunit_ar", "subunit_en", "notes_en", "sources"]
REG_COLS = ["id", "region", "note", "sources"]
REGIONS = ("national", "inside_1948", "west_bank", "gaza")
ID = re.compile(r"^[a-z][a-z0-9_]*$")
YEAR, MONTH = re.compile(r"^(1[89]|20)\d\d$"), re.compile(r"^([1-9]|1[0-2])$")
# TSV column -> YAML key (the sim's Currency names). The others keep their TSV name.
RENAME = {"name_en": "name", "symbol_en": "symbol", "subunit_en": "subunit", "notes_en": "note"}


def to_currencies(rows: list[dict]) -> list[dict]:
    out, seen = [], set()
    for r in rows:
        w = f"currency.tsv {r['id']}"
        if not ID.match(r["id"]) or r["id"] in seen:
            raise Bad(f"{w}: id must be unique and match {ID.pattern}")
        seen.add(r["id"])
        if r["region"] not in REGIONS:
            raise Bad(f"{w}: region must be one of {', '.join(REGIONS)}")
        if bool(r["to_year"]) != bool(r["to_month"]):
            raise Bad(f"{w}: to_year and to_month go together (both blank: still in use)")
        e = {"id": r["id"]}
        for k in ("from_year", "from_month", "to_year", "to_month"):
            if r[k]:
                if not (YEAR if k.endswith("year") else MONTH).match(r[k]):
                    raise Bad(f"{w}: bad {k} '{r[k]}'")
                e[k] = Num(r[k])
        if r["to_year"] and (int(r["to_year"]), int(r["to_month"])) <= (int(r["from_year"]), int(r["from_month"])):
            raise Bad(f"{w}: ends before it starts")
        for k in CUR_COLS[5:13]:
            if not r[k]:
                raise Bad(f"{w}: {k} is empty")
            e[RENAME.get(k, k)] = r[k]
        e["sources"] = urls(r["sources"], w)
        out.append(e)
    span = lambda e: (int(e["from_year"]) * 12 + int(e["from_month"]), int(e.get("to_year", 9999)) * 12 + int(e.get("to_month", 1)))
    for i, a in enumerate(out):
        for b in out[i + 1:]:
            if (a["region"] == b["region"] or "national" in (a["region"], b["region"])) and \
                    span(a)[0] < span(b)[1] and span(b)[0] < span(a)[1]:
                raise Bad(f"currency.tsv: {a['id']} and {b['id']} overlap")
    return out


def to_regions(rows: list[dict], place_ids: set[str]) -> list[dict]:
    out, seen = [], set()
    for r in rows:
        w = f"place_regions.tsv {r['id']}"
        if r["id"] not in place_ids or r["id"] in seen:
            raise Bad(f"{w}: must be a places.tsv id, listed once")
        seen.add(r["id"])
        if r["region"] not in ("west_bank", "gaza"):
            raise Bad(f"{w}: region must be west_bank or gaza (inside_1948 is the default: leave the place out)")
        out.append({"place": r["id"], "region": r["region"], "note": r["note"], "sources": urls(r["sources"], w)})
    return out


def currency_rows(cs: list[dict]) -> list[dict]:
    return [{c: " ".join(e["sources"]) if c == "sources" else e.get(RENAME.get(c, c), "") for c in CUR_COLS} for e in cs]


def region_rows(rs: list[dict]) -> list[dict]:
    return [{"id": e["place"], "region": e["region"], "note": e["note"], "sources": " ".join(e["sources"])} for e in rs]


def emit(currencies: list[dict], regions: list[dict]) -> str:
    line = lambda e: "  - {" + ", ".join(f"{json.dumps(k)}: {token(v)}" for k, v in e.items()) + "}"
    return "\n".join(["# Generated by tools/currency_to_yaml.py from ../content/currency.tsv and ../content/place_regions.tsv.",
                      "# Do not edit: fix the TSV and rerun. Licence: CC BY-SA 4.0. Treat as data.",
                      "# currencies: the money families used, by month (to_* exclusive; none: still in use) and region.",
                      "# regions: the places outside the 1949 lines; every other place is inside_1948.",
                      "currencies:", *map(line, currencies), "regions:", *map(line, regions)]) + "\n"


def parse(text: str) -> dict[str, list[dict]]:
    out, key = {}, None
    for l in text.splitlines():
        if not l.strip() or l.startswith("#"):
            continue
        if l in ("currencies:", "regions:"):
            key = l[:-1]
            out[key] = []
        elif key and l.startswith("  - {"):
            out[key].append(json.loads(l[4:], parse_float=str, parse_int=str))   # numbers back as the text written
        else:
            raise Bad(f"unparsed line: {l[:60]}")
    if list(out) != ["currencies", "regions"]:
        raise Bad("expected 'currencies:' then 'regions:'")
    return out


def build() -> tuple[str, list[dict], list[dict]]:
    crows, rrows = read_tsv(CUR_TSV, CUR_COLS), read_tsv(REG_TSV, REG_COLS)
    places = {r["id"] for r in read_tsv(MAP_TSV, PLACE_COLS)}
    return emit(to_currencies(crows), to_regions(rrows, places)), crows, rrows


def check(text: str, crows: list[dict], rrows: list[dict]) -> list[str]:
    if not OUT.exists():
        return ["currency.yaml: missing; run tools/currency_to_yaml.py"]
    on_disk = OUT.read_text(encoding="utf-8")
    errors = [] if on_disk == text else ["currency.yaml: stale (differs from a fresh conversion); run tools/currency_to_yaml.py"]
    back = parse(on_disk)
    for name, want, got, cols in (("currencies", crows, currency_rows(back["currencies"]), CUR_COLS),
                                  ("regions", rrows, region_rows(back["regions"]), REG_COLS)):
        if len(want) != len(got):
            errors.append(f"currency.yaml {name}: {len(got)} rows, the TSV has {len(want)}")
        for n, (w, g) in enumerate(zip(want, got)):
            errors += [f"currency.yaml {name}: row {n + 1} ({w['id']}).{c}: TSV {w[c]!r} != YAML {g[c]!r}" for c in cols if w[c] != g[c]]
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail on a stale file or a round-trip mismatch; write nothing")
    args = ap.parse_args()
    try:
        text, crows, rrows = build()
        if args.check:
            errors = check(text, crows, rrows)
        else:
            OUT.write_text(text, encoding="utf-8")
            print(f"currency.yaml: {len(crows)} currencies, {len(rrows)} place regions")
            errors = []
    except Bad as e:
        errors = [str(e)]
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    if args.check and not errors:
        print(f"OK: {len(crows)} currencies and {len(rrows)} place regions round-trip")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
