#!/usr/bin/env python3
"""Convert the in-game credits text into the game's YAML (F5 step 9): palestine/credits.yaml, the Credits screen's data.

Stdlib only. Run from anywhere:
    python3 game/tools/credits_to_yaml.py           # write game/content/palestine/credits.yaml
    python3 game/tools/credits_to_yaml.py --check   # exit 1 if the file is stale (differs from a fresh conversion)

Input (read-only here): docs/credits.md, its "## English" and "## العربية" parts. Each "### " heading starts a section;
under it every paragraph, list item and quoted notice is one block, its soft-wrapped lines joined with a space, as
Markdown reads them. **bold** becomes <b>bold</b> (the UI's rich text). A quoted notice is legal text, shown as written in
its original language and left to right: its kind is "quote". The notes above the first "---" are for the screen's
makers, not the player, and are not carried over. One JSON line a section, as places_to_yaml.py writes its entries.
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from places_to_yaml import GAME, OUT_DIR, Bad

MD = GAME / "docs" / "credits.md"
OUT = OUT_DIR / "credits.yaml"
PARTS = {"## English": "en", "## العربية": "ar"}
BOLD = re.compile(r"\*\*(.+?)\*\*")


def sections(md: str) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    lang = None
    section: dict | None = None
    block: dict | None = None

    def close() -> None:
        nonlocal block
        if block is not None and section is not None:
            block["text"] = BOLD.sub(r"<b>\1</b>", " ".join(block["text"]))
            section["blocks"].append(block)
        block = None

    for n, raw in enumerate(md.splitlines(), 1):
        line = raw.rstrip()
        if line in PARTS:
            close()
            lang, section = PARTS[line], None
            out[lang] = []
            continue
        if lang is None or line == "---":
            continue
        if line.startswith("### "):
            close()
            section = {"title": line[4:].strip(), "blocks": []}
            out[lang].append(section)
        elif section is None:
            if line.strip():
                raise Bad(f"credits.md:{n}: text before the part's first ### heading")
        elif not line.strip():
            close()
        elif line.startswith("- "):
            close()
            block = {"kind": "item", "text": [line[2:].strip()]}
        elif line.startswith("> "):
            if block is None or block["kind"] != "quote":
                close()
                block = {"kind": "quote", "text": []}
            block["text"].append(line[2:].strip())
        elif line.startswith("  ") and block is not None and block["kind"] == "item":
            block["text"].append(line.strip())
        elif line.startswith("#") or line.startswith(">"):
            raise Bad(f"credits.md:{n}: unexpected line: {line[:40]}")
        else:
            if block is None or block["kind"] != "text":
                close()
                block = {"kind": "text", "text": []}
            block["text"].append(line.strip())
    close()
    if sorted(out) != ["ar", "en"]:
        raise Bad("credits.md: needs an '## English' and an '## العربية' part")
    for lang, secs in out.items():
        if not secs or any(not s["blocks"] for s in secs):
            raise Bad(f"credits.md ({lang}): every part needs sections, and every section text")
    return out


def emit(parts: dict[str, list[dict]]) -> str:
    lines = ["# Generated by tools/credits_to_yaml.py from docs/credits.md. Do not edit: fix the Markdown and rerun.",
             "# The Credits screen (Settings): one section a line, its blocks text, item (a list item) or quote (a notice shown",
             "# as written, left to right). <b> is the UI's rich text."]
    for lang in ("en", "ar"):
        lines.append(f"{lang}:")
        lines += ["  - " + json.dumps(s, ensure_ascii=False) for s in parts[lang]]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail on a stale file; write nothing")
    args = ap.parse_args()
    try:
        parts = sections(MD.read_text(encoding="utf-8"))
        text = emit(parts)
        if args.check:
            errors = [] if OUT.exists() and OUT.read_text(encoding="utf-8") == text else \
                ["credits.yaml: stale or missing; run tools/credits_to_yaml.py"]
        else:
            OUT.write_text(text, encoding="utf-8")
            errors = []
        counts = ", ".join(f"{len(parts[k])} {k} sections" for k in ("en", "ar"))
    except Bad as e:
        errors, counts = [str(e)], ""
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    if not errors:
        print(("OK: " if args.check else "credits.yaml: ") + counts)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
